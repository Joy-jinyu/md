export function handwriting(phrase, x, baseline, size) {
  const scale = size / 29;
  const strokes = [];
  for (const character of phrase) {
    if (character === " ") {
      x += 8 * scale;
      continue;
    }
    const [advance, ...paths] = alphabet[character];
    for (const path of paths) {
      strokes.push(path.map(([u, v]) => [x + u * scale, baseline - v * scale]));
    }
    x += (advance + 1.5) * scale;
  }
  strokes.push([
    [x + 2 * scale, baseline - 2],
    [x + 2.8 * scale, baseline - 2.8],
  ]);
  return strokes;
}
